    private fun rows(code: String) = QrPattern.modules(code).map { row -> row.joinToString("") { if (it) "1" else "0" } }

    @Test
    fun matchesTheDesignForEachCode() {
        assertEquals(fado_001, rows("HO-FADO-001"), "HO-FADO-001")
        assertEquals(fado_002, rows("HO-FADO-002"), "HO-FADO-002")
        assertEquals(nigh_001, rows("HO-NIGH-001"), "HO-NIGH-001")
    }

    @Test
    fun isA25ModuleSquareWithThreeFinders() {
        val grid = QrPattern.modules("HO-FADO-001")
        assertEquals(25, grid.size)
        grid.forEach { assertEquals(25, it.size) }
        listOf(0 to 0, 18 to 0, 0 to 18).forEach { (ox, oy) ->
            assertEquals(true, grid[oy][ox], "finder corner at $ox,$oy")
            assertEquals(true, grid[oy + 3][ox + 3], "finder center at $ox,$oy")
            assertEquals(false, grid[oy + 1][ox + 1], "finder ring gap at $ox,$oy")
        }
        assertEquals(true, grid[18][18], "alignment center")
    }

    @Test
    fun isDeterministicAndDiffersPerCode() {
        assertEquals(rows("HO-FADO-002"), rows("HO-FADO-002"))
        assertNotEquals(rows("HO-FADO-001"), rows("HO-FADO-002"))
    }
